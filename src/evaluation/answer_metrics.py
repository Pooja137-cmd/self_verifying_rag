"""SQuAD-style answer metrics for short-answer QA."""
from __future__ import annotations

import re
import string
from collections import Counter


def normalize_answer(s: str) -> str:
    s = s.lower()
    s = "".join(ch for ch in s if ch not in set(string.punctuation))
    s = re.sub(r"\b(a|an|the)\b", " ", s)
    return " ".join(s.split())


def exact_match(pred: str, gold: str) -> float:
    return float(normalize_answer(pred) == normalize_answer(gold))


def contains_gold(pred: str, gold: str) -> float:
    """Lenient: gold answer appears inside the prediction (useful for verbose small models)."""
    g = normalize_answer(gold)
    return float(bool(g) and g in normalize_answer(pred))


def f1_score(pred: str, gold: str) -> float:
    p, g = normalize_answer(pred).split(), normalize_answer(gold).split()
    if not p or not g:
        return float(p == g)
    common = Counter(p) & Counter(g)
    n = sum(common.values())
    if n == 0:
        return 0.0
    prec, rec = n / len(p), n / len(g)
    return 2 * prec * rec / (prec + rec)


def is_abstention(pred: str) -> bool:
    return "insufficient information" in pred.lower()